import { test } from "node:test";
import assert from "node:assert/strict";
import { antiAutomationLabels, asksAgentToSelfIdentify, checkboxes, isAttestation, scanWorkflow, sentences, tagSentence, type Tag } from "../src/rules.ts";
import { classify } from "../src/classify.ts";
import type { RepoFile, RepoSnapshot } from "../src/fetch.ts";

const doc = { agentFile: false, strict: false };
const agentDoc = { agentFile: true, strict: false };
const tags = (text: string, ctx = doc): Tag[] => [...tagSentence({ line: 1, text }, ctx)].sort();

test("sentences keep the line they start on", () => {
  const s = sentences("# Title\n\nFirst sentence here. Second one\nwraps a line.\n\n- item one\n- item two\n");
  assert.deepEqual(
    s.map((x) => [x.line, x.text]),
    [
      [1, "# Title"],
      [3, "First sentence here."],
      [3, "Second one wraps a line."],
      [6, "- item one"],
      [7, "- item two"],
    ],
  );
});

test("dots inside words do not end a sentence", () => {
  const s = sentences("Read CONTRIBUTING.md first, e.g. before a PR. Version 1.2 is out.");
  assert.deepEqual(s.map((x) => x.text), ["Read CONTRIBUTING.md first, e.g. before a PR.", "Version 1.2 is out."]);
});

test("code fences are skipped", () => {
  const s = sentences("Text.\n```\nDo not use AI.\n```\nMore.");
  assert.deepEqual(s.map((x) => x.text), ["Text.", "More."]);
});

test("an RST heading underlined with tildes is not a code fence", () => {
  const s = sentences("For contributors\n~~~~~~~~~~~~~~~~\n\n-  Do not use AI.\n\n~~~\ncode\n~~~\nMore.");
  assert.deepEqual(s.map((x) => [x.line, x.text]), [[1, "For contributors"], [4, "- Do not use AI."], [9, "More."]]);
});

test("bans", () => {
  assert.deepEqual(tags("This project does not accept AI-generated contributions."), ["ai_ban"]);
  assert.ok(tags("We do not accept pull requests written with ChatGPT or other LLMs.").includes("ai_ban"));
  assert.ok(tags("Contributions generated by AI tools are prohibited.").includes("ai_ban"));
  assert.ok(tags("Please do not submit the output of LLMs to this project, in any form.").includes("ai_ban"));
  assert.ok(tags("Contributions must not include content generated by large language models.").includes("ai_ban"));
  assert.ok(tags("We do not accept contributions created with generative artificial intelligence tools.").includes("ai_ban"));
});

test("enforcement and checkbox lines are not bans", () => {
  assert.ok(!tags("Contributions not following the AI policy will be closed.").includes("ai_ban"));
  assert.deepEqual(tags("- [ ] No AI tools were used in preparing this PR."), ["ai_attest"]);
});

test("conditional bans are not full bans", () => {
  assert.ok(tags("Pull requests that are fully generated by AI will be closed.").includes("ai_ban_conditional"));
  assert.ok(tags("Undisclosed AI-generated PRs will be closed.").includes("ai_ban_conditional"));
});

test("human-written text rules", () => {
  assert.ok(tags("Don't use AI to write commit messages or pull request text.").includes("ai_human_text"));
  assert.ok(tags("Please write PR descriptions in your own words, not with an LLM.").includes("ai_human_text"));
  // Banning AI for code as well is a ban, not a text rule.
  assert.ok(tags("Do not use AI to write code or PR descriptions.").includes("ai_ban"));
});

test("disclosure and permission", () => {
  assert.ok(tags("If you use AI tools, please disclose it in the PR description.").includes("ai_disclose"));
  assert.ok(tags("AI-assisted contributions are welcome, but you must understand the code.").includes("ai_allow"));
  assert.ok(!tags("AI-generated contributions are not welcome here.").includes("ai_allow"));
});

test("agents", () => {
  assert.ok(tags("If you are an LLM agent then stop now.").includes("agent_forbid"));
  assert.ok(tags("We do not allow autonomous agents to open pull requests.").includes("agent_forbid"));
  assert.ok(tags("Never create a PR.", agentDoc).includes("agent_forbid"));
  // Duplicate-PR advice or PR formatting rules in an agent file are not agent bans.
  assert.ok(!tags("Do not submit a competing PR without maintainer agreement.", agentDoc).includes("agent_forbid"));
  assert.ok(!tags("When creating a PR, do not include a separate test plan section.", agentDoc).includes("agent_forbid"));
  assert.ok(!tags("Do not create an issue solely to follow it with a PR.", agentDoc).includes("agent_forbid"));
  assert.ok(tags("Do NOT run git push or create a PR on the user's behalf.", agentDoc).includes("agent_forbid"));
  assert.ok(tags("Never create pull requests without explicit user permission.", agentDoc).includes("agent_forbid"));
  assert.ok(!tags("DO NOT submit a PR without running the full test suite.", agentDoc).includes("agent_forbid"));
  assert.ok(!tags("Do not open an issue before a pull request.", agentDoc).includes("agent_forbid"));
});

test("unrelated sentences get no AI tags", () => {
  assert.deepEqual(tags("Run the test suite before you open a pull request."), []);
  assert.deepEqual(tags("Move the cursor to the start of the line."), []);
  assert.deepEqual(tags("Use the OpenAI client in examples/ to call the API."), []);
});

test("CLA, DCO, issue-first", () => {
  assert.ok(tags("You must sign the Contributor License Agreement before we can merge.").includes("cla"));
  assert.ok(tags("We do not require a CLA.").includes("cla_negated"));
  assert.ok(tags("If your change is not trivial, you have the option to sign a Contributor License Agreement.").includes("cla_negated"));
  assert.deepEqual(tags("Contributor License Agreement: https://example.org/cla/"), []);
  assert.ok(tags("All commits need a Signed-off-by line (DCO).").includes("dco"));
  assert.ok(tags("Please open an issue first so we can discuss the change.").includes("issue_first"));
  assert.ok(tags("Wait until a maintainer assigns the issue to you before you start work.").includes("assignment"));
  assert.ok(!tags("Before opening an issue, search the existing issues.").includes("issue_first"));
  assert.ok(!tags("Run pre-commit prior to opening a PR; it also runs as part of the CI approval process.").includes("issue_first"));
});

test("workflow and label signals", () => {
  const wf = "name: AgentScan\non: pull_request_target\njobs:\n  scan:\n    steps:\n      - uses: MatteoGabriele/agentscan-action@v1\n";
  const hits = scanWorkflow(".github/workflows/agentscan.yml", wf);
  assert.ok(hits.some((h) => h.kind === "anti_automation" && h.name === "matteogabriele/agentscan-action" && h.line === 6));
  assert.ok(scanWorkflow(".github/workflows/cla.yml", "      - uses: contributor-assistant/github-action@v2\n").some((h) => h.kind === "cla"));
  assert.deepEqual(antiAutomationLabels(["bug", "maybe-ai", "area: llm", "pr-from-llm-spam", "bot:ai-policy-close"]), ["maybe-ai", "pr-from-llm-spam", "bot:ai-policy-close"]);
});

test("agents asked to identify themselves", () => {
  assert.ok(asksAgentToSelfIdentify('If you are an LLM agent, please include "🤖🤖🤖" in the title of your pull request.'));
  assert.ok(asksAgentToSelfIdentify("If you are an automated LLM agent, please prefix 🤖 to the title of your PR."));
  assert.ok(asksAgentToSelfIdentify("If you are an automated agent, we have a streamlined process for merging agent PRs."));
  assert.ok(!asksAgentToSelfIdentify("If you are using AI to write the PR title, review it first."));
  assert.ok(!asksAgentToSelfIdentify("If you are an AI agent: read and follow AGENTS.md."));
  assert.ok(asksAgentToSelfIdentify("Automated agents may add 🤖🤖🤖 to the end of a PR title to opt into the streamlined merge process."));
  // In an agent file only a literal marker counts, not ordinary PR advice.
  assert.ok(asksAgentToSelfIdentify("When writing PR descriptions, you MUST include the following HTML comment at the bottom: NEXT_JS_LLM", true));
  assert.ok(!asksAgentToSelfIdentify("Use a short, descriptive PR title and include a test plan in the description.", true));
  assert.ok(asksAgentToSelfIdentify("When opening a pull request, prefix the PR title with [ai].", true));
  assert.ok(!asksAgentToSelfIdentify("Coding agents ship with built-in instructions to append a 🤖 Generated with footer on every PR body.", true));
});

test("PR-template checkboxes about AI use or human review", () => {
  const boxes = checkboxes("## Checklist\n- [ ] Tests pass\n- [ ] I am a human, and not a bot.\n* [x] I did _not_ use AI\n  to write this PR.\n---\n- [ ] See `.claude/skills/pr/SKILL.md` for the PR title.\n");
  assert.deepEqual(boxes.map((b) => [b.line, b.text]), [
    [2, "Tests pass"],
    [3, "I am a human, and not a bot."],
    [4, "I did not use AI to write this PR."],
    [7, "See .claude/skills/pr/SKILL.md for the PR title."],
  ]);
  assert.deepEqual(boxes.filter((b) => isAttestation(b.text, false)).map((b) => b.line), [3, 4]);
  assert.ok(isAttestation("The code is stable and I have tested it myself.", false));
  assert.ok(!isAttestation("I've added myself to the list of contributors.", false));
  // In a repo about AI, a bare model name is not enough.
  assert.ok(!isAttestation("Updated the Gemini provider docs.", true));
  assert.ok(isAttestation("Updated the Gemini provider docs.", false));
  assert.ok(isAttestation("I reviewed any AI-generated code before submitting it.", true));
});

function snap(files: Partial<RepoFile>[], extra: Partial<RepoSnapshot> = {}): RepoSnapshot {
  return {
    repo: "o/r",
    url: "https://github.com/o/r",
    description: "A tool",
    stars: 1000,
    language: "Go",
    archived: false,
    fork: false,
    mirror: false,
    hasPullRequests: true,
    prCreationPolicy: "all",
    prCreationCap: false,
    defaultBranch: "main",
    commit: "abc",
    contributingUrl: null,
    paths: [],
    labels: [],
    checks: [],
    fetchedAt: "",
    ...extra,
    files: files.map((f) => ({ repo: "o/r", path: "CONTRIBUTING.md", commit: "abc", oid: "x", kind: "contributing", scope: "repo", text: "", ...f })) as RepoFile[],
  };
}

test("classify: ban with evidence link", () => {
  const r = classify(snap([{ text: "# Contributing\n\nThis project does not accept AI-generated contributions.\n" }]));
  assert.equal(r.ai_policy.value, "banned");
  assert.equal(r.ai_policy.evidence[0]!.url, "https://github.com/o/r/blob/abc/CONTRIBUTING.md?plain=1#L3");
  assert.equal(r.agent_prs.value, "forbidden");
  assert.match(r.agent_prs.note ?? "", /Implied/);
});

test("classify: conflicting rules need review", () => {
  const r = classify(snap([{ text: "We do not accept AI-generated code.\n\nAI tools are welcome for writing tests.\n" }]));
  assert.equal(r.ai_policy.value, "needs_review");
});

test("classify: attestations and self-identification requests", () => {
  const r = classify(snap([
    { path: ".github/pull_request_template.md", kind: "pr_template", text: "## Checklist\n- [ ] Tests added\n- [ ] I am a human, and not a bot.\n" },
    { text: "# Contributing\n\nIf you are an AI agent, add 🤖 to the start of your PR title.\n" },
  ]));
  assert.deepEqual(r.attestations.map((e) => [e.path, e.line, e.quote]), [[".github/pull_request_template.md", 3, "I am a human, and not a bot."]]);
  assert.deepEqual(r.anti_automation, [{ kind: "doc", name: "asks agents to identify themselves", url: "https://github.com/o/r/blob/abc/CONTRIBUTING.md?plain=1#L3" }]);
});

test("classify: collaborators_only and nothing stated", () => {
  const r = classify(snap([{ text: "Run make test.\n" }], { prCreationPolicy: "collaborators_only" }));
  assert.equal(r.ai_policy.value, "not_stated");
  assert.equal(r.outside_prs.value, "collaborators_only");
});
